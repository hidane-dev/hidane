pub fn verified(ecosystem: &str, name: &str) -> Option<&'static Verified> {
    VERIFIED
        .iter()
        .find(|v| v.ecosystem == ecosystem && v.name == name)
}

impl Verified {
    pub fn major(&self) -> u64 {
        super::deps::major(self.version).unwrap_or(0)
    }
}

